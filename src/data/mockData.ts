type RoleInboxKind = 'officer' | 'land' | 'industry';

function createRoleInboxRequests(
  kind: RoleInboxKind,
  idPrefix: string,
  numberBase: number,
): ReclamationRequest[] {
  return Array.from({ length: 25 }, (_, index) => {
    const number = index + 1;
    const place = MANAGER_STAGE_PLACES[index % MANAGER_STAGE_PLACES.length];
    const createdAt = `2026-04-${String((number % 27) + 1).padStart(2, '0')}T08:00:00.000Z`;
    const reviewedAt = `2026-04-${String((number % 27) + 1).padStart(2, '0')}T11:00:00.000Z`;
    const updatedAt = `2026-04-${String((number % 27) + 1).padStart(2, '0')}T14:30:00.000Z`;
    const requestId = `${idPrefix}-${String(number).padStart(3, '0')}`;
    const referredToLand = kind === 'land';
    const referredToIndustry = kind === 'industry';

    const history: ReclamationRequest['history'] = [
      {
        id: `${requestId}-h1`,
        stage: 'تقديم الطلب',
        actorName: 'محمد محمد المطيري',
        actorRole: 'مستفيد',
        date: createdAt,
        action: 'تقديم طلب استصلاح زراعي جديد',
      },
    ];

    if (kind !== 'officer') {
      history.push(
        {
          id: `${requestId}-h2`,
          stage: 'مراجعة موظف الفرع',
          actorName: 'خالد عبدالرحمن العتيبي',
          actorRole: 'موظف الفرع',
          date: reviewedAt,
          action: 'قبول وتحويل إلى مدير الفرع',
        },
        {
          id: `${requestId}-h3`,
          stage: 'مراجعة مدير الفرع',
          actorName: 'سعود فهد القحطاني',
          actorRole: 'مدير الفرع',
          date: updatedAt,
          action: referredToLand
            ? 'إحالة إلى موظف وكالة الأراضي'
            : 'إحالة إلى ممثل وزارة الصناعة',
        },
      );
    }

    return {
      id: requestId,
      requestNumber: `REQ-2026-${String(numberBase + number)}`,
      status:
        kind === 'officer' ? 'pending_branch_officer' : 'referred_to_agencies',
      createdAt,
      updatedAt: kind === 'officer' ? createdAt : updatedAt,
      beneficiaryId: 'u-beneficiary',
      fullName: 'محمد محمد المطيري',
      nationalId: '1087654321',
      mobile: '0501234567',
      email: 'abdullah@example.com',
      applicantType: MANAGER_STAGE_APPLICANTS[index % MANAGER_STAGE_APPLICANTS.length],
      region: place.region,
      governorate: place.governorate,
      siteName: `${place.siteName} ${numberBase + number}`,
      deedNumber: `صك-${String(800000 + numberBase + number)}`,
      area: 4 + (number % 15) + 0.25,
      areaUnit: 'hectare',
      latitude: (24.2 + number / 100).toFixed(6),
      longitude: (43.2 + number / 100).toFixed(6),
      currentUse: 'أرض بور غير مستصلحة',
      waterSource: 'بئر ارتوازي مرخص',
      reclamationPlan: 'استصلاح الأرض وزراعة محاصيل وفق الخطة المعتمدة.',
      surveyReport: samplePdf,
      referredToLand,
      referredToIndustry,
      history,
    };
  });
}

